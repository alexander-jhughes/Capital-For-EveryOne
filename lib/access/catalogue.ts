// What Dial knows about adapting itself. Each situation is something a person might tell Dial about themselves, in
// their own words, with example sentences (what the on-device model compares against), the changes that help, and a
// plain reason for each change that Dial shows before anything is kept.
//
// Nothing here is a diagnosis and nothing is stored about the person: only the settings they keep are saved. The
// examples teach the model what each situation sounds like; the changes are fixed, tested code. The AI never picks a
// setting directly: it can only point at a situation in this list.
