// Measures how well Dial understands people describing their situation, using exactly the code the app runs
// (lib/access/pipeline.ts) and the same model, loaded from public/models. Writes docs/ACCESS-EVALUATION.md.
// Usage: npm run access:eval
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { adaptationFor, offeredAdaptation } from "../../lib/access/pipeline";
import { buildIndex } from "../../lib/access/understand";
import { EVAL_SET, TEST_SET, type EvalCase } from "../../lib/access/eval-set";
import type { SituationId } from "../../lib/access/catalogue";
import { THRESHOLDS } from "../../lib/access/understand";
import { interpret } from "../../lib/voice/interpret";
import { nodeEmbed } from "./embed-node";

const embed = nodeEmbed();
const index = await buildIndex(embed);
const brain = { embed, index };

interface Row {
  c: EvalCase;
  got: SituationId[];
  scope?: string;
  tentative: boolean;
  oldChanged: boolean;
  ms: number;
}

async function run(set: EvalCase[]): Promise<Row[]> {
  const rows: Row[] = [];
  for (const c of set) {
    const t0 = performance.now();
    const a = await adaptationFor(c.text, brain);
    const ms = performance.now() - t0;
    // The precise rules "gave up" when they found nothing to do; only then may a tentative result be offered.
    const rules = interpret(c.text);
    const offered = offeredAdaptation(a, rules.kind === "unknown");
    rows.push({ c, got: offered?.situations ?? [], scope: offered?.scope, tentative: !!offered?.tentative, oldChanged: rules.kind === "ui", ms });
  }
  return rows;
}

const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${((100 * n) / d).toFixed(0)}%`);
const same = (a: readonly string[], b: readonly string[]) => a.length === b.length && a.every((x) => b.includes(x));

function summarise(name: string, rows: Row[]) {
  const pos = rows.filter((r) => r.c.expect.length > 0);
  const neg = rows.filter((r) => r.c.expect.length === 0);
  const exact = pos.filter((r) => same(r.got, r.c.expect)).length;
  const first = pos.filter((r) => r.got.length > 0 && r.c.expect.includes(r.got[0])).length;
  const anything = pos.filter((r) => r.got.length > 0).length;
  const wrong = pos.filter((r) => r.got.length > 0 && !r.got.some((g) => r.c.expect.includes(g))).length;
  const hijack = neg.filter((r) => r.got.length > 0).length;
  const scoped = pos.filter((r) => r.c.scope && same(r.got, r.c.expect));
  const scopeOk = scoped.filter((r) => r.scope === r.c.scope).length;
  const oldAny = pos.filter((r) => r.oldChanged).length;
  // For commands, changing the look is the right answer, so the old rules are only judged on the rest.
  const notCommands = neg.filter((r) => r.c.group !== "command");
  const oldHijack = notCommands.filter((r) => r.oldChanged).length;
  const ms = rows.map((r) => r.ms).sort((a, b) => a - b);
  return {
    name,
    lines: [
      `| Described situations recognised (exactly right) | ${pct(exact, pos.length)} (${exact}/${pos.length}) |`,
      `| Main situation right | ${pct(first, pos.length)} (${first}/${pos.length}) |`,
      `| Offered anything for a described situation | ${pct(anything, pos.length)} (${anything}/${pos.length}) |`,
      `| Offered the wrong situation | ${pct(wrong, pos.length)} (${wrong}/${pos.length}) |`,
      `| Money questions, commands, denials and chat wrongly treated as a situation | ${pct(hijack, neg.length)} (${hijack}/${neg.length}) |`,
      `| "When" right (night, now, always), where the sentence says | ${pct(scopeOk, scoped.length)} (${scopeOk}/${scoped.length}) |`,
      `| Old keyword rules: changed anything for a described situation | ${pct(oldAny, pos.length)} (${oldAny}/${pos.length}) |`,
      `| Old keyword rules: changed the look for a money question, denial or small talk | ${pct(oldHijack, notCommands.length)} (${oldHijack}/${notCommands.length}) |`,
      `| Median time per sentence (Node, one CPU thread) | ${ms[Math.floor(ms.length / 2)].toFixed(0)} ms |`,
    ],
    misses: rows.filter((r) => !same(r.got, r.c.expect)).map((r) => `| ${r.c.text} | ${r.c.expect.join(" + ") || "nothing"} | ${r.got.join(" + ") || "nothing"}${r.tentative ? " (asked)" : ""} |`),
    exact,
    pos: pos.length,
    hijack,
  };
}

const dev = summarise("Development set", await run(EVAL_SET));
const test = summarise("Blind test set", await run(TEST_SET));

const report = `# Understanding people who describe their situation

Generated by \`npm run access:eval\` (scripts/access/evaluate.ts). It runs exactly the code Dial runs
(\`lib/access/pipeline.ts\`) with the same on-device model (all-MiniLM-L6-v2, 8-bit, from \`public/models\`).

**What is measured:** a person tells Dial something about themselves ("I have trouble seeing at night", "my hands
shake", "u talk 2 fast"). Dial should recognise the situation and offer the right changes, and must *not* treat money
questions ("I can't see my refund"), direct commands ("make the text bigger"), denials ("I'm not colour blind") or
small talk as a situation.

**How it was built and tested:**

- The model compares meaning, not keywords: each sentence is turned into a 384-number vector and compared with the
  catalogue's example sentences (\`lib/access/catalogue.ts\`, ${index.labels.length} examples).
- Thresholds (accept ${THRESHOLDS.accept}, gap ${THRESHOLDS.margin}; "maybe" ${THRESHOLDS.maybe}, gap ${THRESHOLDS.maybeMargin}) were chosen by
  leave-one-out over the catalogue's own examples, never on these sets.
- The **development set** was used while building. The **blind test set** was written afterwards and nothing was
  changed after seeing its results. Quote the blind test numbers.
- None of these sentences appear in the catalogue.

## Blind test set (${TEST_SET.length} sentences)

| Measure | Result |
|---|---|
${test.lines.join("\n")}

## Development set (${EVAL_SET.length} sentences)

| Measure | Result |
|---|---|
${dev.lines.join("\n")}

## What it got wrong (blind test set)

| Sentence | Expected | Dial offered |
|---|---|---|
${test.misses.join("\n") || "| (none) | | |"}

## What it got wrong (development set)

| Sentence | Expected | Dial offered |
|---|---|---|
${dev.misses.join("\n") || "| (none) | | |"}

## Why mistakes are cheap

Every adaptation is a preview with a reason for each change. Nothing is kept until the person says "Keep it", and
"Undo" always works. A wrong guess costs one tap; a missed one falls through to the precise rules and then to the
cloud model, which may only name a situation from the same catalogue. The one mistake that would really cost the
person is a money question turned into a display change, which is why that number is reported separately.
`;

writeFileSync(fileURLToPath(new URL("../../docs/ACCESS-EVALUATION.md", import.meta.url)), report);
console.log(`Blind test: ${test.exact}/${test.pos} exactly right, ${test.hijack} non-situations hijacked. Development: ${dev.exact}/${dev.pos}, ${dev.hijack} hijacked.`);
console.log("Wrote docs/ACCESS-EVALUATION.md");
