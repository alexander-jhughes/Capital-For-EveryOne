// Trains the person-type profile model on SYNTHETIC data and writes:
//   lib/profile/model.json               the trained softmax model (committed, loaded by the server)
//   docs/profile-model/EVALUATION.md     metrics, baselines and per-type results
//
// Usage (Node 22.15+ or 24, no extra packages):
//   node --no-warnings --import ./scripts/personalisation/ts-resolve.mjs scripts/profile/train.ts
// Add --check to train and compare with the committed model without writing anything (exit 1 if different).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PERSON_TYPE_COPY, PERSON_TYPES } from "../../lib/profile/catalog";
import { DEFAULT_CONFIG, trainModel, type Metrics } from "../../lib/profile/train";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const modelPath = join(root, "lib", "profile", "model.json");
const reportPath = join(root, "docs", "profile-model", "EVALUATION.md");

const started = performance.now();
const { model, report } = trainModel(DEFAULT_CONFIG);
const seconds = ((performance.now() - started) / 1000).toFixed(1);
const json = JSON.stringify(model);

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(modelPath, "utf8").replace(/\r\n/g, "\n").trim();
  } catch {}
  if (committed !== json) {
    console.error("The committed model differs from a fresh training run. Retrain and commit lib/profile/model.json.");
    process.exit(1);
  }
  console.log(`Model matches a fresh training run (${seconds} s).`);
  process.exit(0);
}

const pct = (v: number) => `${(v * 100).toFixed(1)}%`;
const row = (name: string, m: Metrics, gated = false) =>
  `| ${name} | ${pct(m.accuracy)} | ${m.macroF1.toFixed(3)} | ${m.logLoss.toFixed(3)} | ${m.ece.toFixed(3)} | ${gated ? `${pct(m.coverage)} / ${pct(m.confidentAccuracy)}` : "n/a"} |`;

const md = `# Profile model: evaluation

Generated by \`scripts/profile/train.ts\`. Do not edit by hand.

- Model: \`${model.version}\`, softmax regression over ${model.features.length} features, ${model.classes.length} person types
- Data: **synthetic only** (generator v${model.generatorVersion}, seed ${report.config.seed}): ${report.config.train} train, ${report.config.validation} validation, ${report.config.test} test
- Training: ${report.config.epochs} epochs, learning rate ${report.config.learningRate}, L2 ${report.config.l2}, ${seconds} s
- Calibration: temperature ${model.temperature} chosen on validation log loss
- Threshold: ${model.threshold} (lowest whose validation accuracy among confident people reaches ${pct(report.config.targetAccuracy)}). Below it the app shows no type and asks.

## Test set

| Model | Accuracy | Macro F1 | Log loss | ECE | Coverage / accuracy at threshold |
|---|---|---|---|---|---|
${row("Profile model", report.test, true)}
${row("Training set (overfitting check)", report.train, true)}
${row("Rule baseline (hand-written)", report.baselines.rules)}
${row("Majority class", report.baselines.majority)}

## Per type (test set)

| Type | Shown as | Precision | Recall | F1 | Support |
|---|---|---|---|---|---|
${PERSON_TYPES.map((t) => {
  const c = report.test.perClass[t];
  return `| \`${t}\` | ${PERSON_TYPE_COPY[t].title} | ${c.precision.toFixed(3)} | ${c.recall.toFixed(3)} | ${c.f1.toFixed(3)} | ${c.support} |`;
}).join("\n")}

## Reading this

These scores show the pipeline learns the structure the generator put in. They do **not** show the model predicts real
people: we wrote the generator. Real use needs consented, real outcomes (did the person keep the type, or change it?)
and a fairness review before any threshold is trusted. See \`README.md\`, "Limitations".
`;

mkdirSync(dirname(reportPath), { recursive: true });
writeFileSync(modelPath, json + "\n");
writeFileSync(reportPath, md);
console.log(`Trained in ${seconds} s. Test accuracy ${pct(report.test.accuracy)}, macro F1 ${report.test.macroF1}, threshold ${model.threshold}.`);
